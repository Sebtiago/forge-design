/* ─── Background switcher ────────────────────────── */
function setBg(slug, bg) {
  const gallery = document.getElementById(`gallery-${slug}`);
  const switcher = document.getElementById(`bg-switcher-${slug}`);
  if (!gallery) return;
  gallery.dataset.bg = bg;
  switcher.querySelectorAll('.bg-btn').forEach(b => b.classList.remove('active'));
  event.target.classList.add('active');
}

