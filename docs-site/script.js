/* Kiro Docs — visual-first for designers */

let DATA = null;
let currentPage = 'overview';
let currentView = 'designer';

async function boot() {
  try {
    const res = await fetch('./data.json');
    DATA = await res.json();
  } catch {
    DATA = getPlaceholderData();
  }
  initTheme();
  initView();
  renderSidebar();
  navigate('overview');
  updateHeader();
}

function updateHeader() {
  const p = document.getElementById('project-name');
  const b = document.getElementById('framework-badge');
  if (DATA.project) p.textContent = DATA.project;
  if (DATA.framework) b.textContent = DATA.framework;
}

/* ─── View toggle ────────────────────────────────── */
function initView() {
  const saved = localStorage.getItem('kiro-view') || 'designer';
  setView(saved, true);
}
function setView(view, silent) {
  currentView = view;
  localStorage.setItem('kiro-view', view);
  document.body.dataset.view = view;
  document.querySelectorAll('.view-btn').forEach(b => b.classList.toggle('active', b.dataset.view === view));
  if (!silent) navigate(currentPage);
}

/* ─── Theme ─────────────────────────────────────── */
function initTheme() {
  const saved = localStorage.getItem('kiro-theme');
  const isDark = saved ? saved === 'dark' : window.matchMedia('(prefers-color-scheme: dark)').matches;
  if (isDark) document.documentElement.setAttribute('data-theme', 'dark');
  updateThemeToggle(isDark);
}
function toggleTheme() {
  const isDark = document.documentElement.getAttribute('data-theme') === 'dark';
  if (isDark) { document.documentElement.removeAttribute('data-theme'); localStorage.setItem('kiro-theme', 'light'); }
  else { document.documentElement.setAttribute('data-theme', 'dark'); localStorage.setItem('kiro-theme', 'dark'); }
  updateThemeToggle(!isDark);
}
function updateThemeToggle(isDark) {
  const btn = document.getElementById('theme-toggle');
  btn.textContent = isDark ? '○' : '●';
}
document.getElementById('theme-toggle').addEventListener('click', toggleTheme);

/* ─── Sidebar ────────────────────────────────────── */
function renderSidebar() {
  const nav = document.getElementById('component-nav');
  const tc = document.getElementById('token-count');
  tc.textContent = Object.keys(DATA.tokens?.colors || {}).length || '—';
  if (!DATA.components?.length) { nav.innerHTML = '<div class="sidebar-item" style="pointer-events:none;opacity:.4">No components</div>'; return; }

  const categories = [
    { key: 'atom',     label: 'Atoms' },
    { key: 'molecule', label: 'Molecules' },
    { key: 'organism', label: 'Organisms' },
  ];

  const grouped = {};
  DATA.components.forEach(c => {
    const cat = c.category || 'atom';
    if (!grouped[cat]) grouped[cat] = [];
    grouped[cat].push(c);
  });

  nav.innerHTML = categories
    .filter(cat => grouped[cat.key]?.length)
    .map(cat => `
      <div class="sidebar-category-label">${cat.label}</div>
      ${grouped[cat.key].map(c => `
        <button class="sidebar-item" onclick="navigate('component:${c.slug}')" data-page="component:${c.slug}">
          ${c.name}
          <span class="sidebar-item-count">${c.variants?.length || 1}</span>
        </button>`).join('')}
    `).join('');
}

/* ─── Navigation ─────────────────────────────────── */
function navigate(page) {
  currentPage = page;
  document.querySelectorAll('.sidebar-item').forEach(el => el.classList.toggle('active', el.dataset.page === page));
  const content = document.getElementById('page-content');
  if (page === 'overview') content.innerHTML = renderOverview();
  else if (page === 'tokens') content.innerHTML = renderTokens();
  else if (page.startsWith('component:')) content.innerHTML = renderComponent(page.replace('component:', ''));
  if (window.Prism) Prism.highlightAll();
  window.scrollTo(0, 0);
}

/* ─── Overview ───────────────────────────────────── */
function renderOverview() {
  const cc = DATA.components?.length || 0;
  const colors = Object.keys(DATA.tokens?.colors || {}).length;
  const date = DATA.generatedAt ? new Date(DATA.generatedAt).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }) : '—';

  const cards = (DATA.components || []).map(c => `
    <a class="component-card" href="#" onclick="navigate('component:${c.slug}');return false;">
      <div class="component-card-thumb">
        ${renderMiniPreview(c)}
      </div>
      <div class="component-card-body">
        <div class="component-card-name">${c.name}</div>
        <div class="component-card-meta">${c.variants?.length || 1} variant${(c.variants?.length || 1) !== 1 ? 's' : ''}</div>
      </div>
    </a>`).join('');

  return `
    <div class="page">
      <div class="page-header">
        <div class="page-eyebrow">Design System</div>
        <h1 class="page-title">${DATA.project || 'Kiro Output'}</h1>
        <p class="page-description">Generated by Kiro · ${date}</p>
      </div>
      <div class="stats-row">
        <div class="stat"><div class="stat-value">${cc}</div><div class="stat-label">Components</div></div>
        <div class="stat"><div class="stat-value">${colors}</div><div class="stat-label">Color tokens</div></div>
        <div class="stat"><div class="stat-value">${Object.keys(DATA.tokens?.spacing || {}).length}</div><div class="stat-label">Spacing steps</div></div>
      </div>
      <div class="section">
        <div class="section-title">Components</div>
        ${cards ? `<div class="component-grid">${cards}</div>` : '<p class="muted">No components yet. Run /figma-to-code to generate.</p>'}
      </div>
    </div>`;
}

/* ─── Component page — VISUAL FIRST ─────────────── */
